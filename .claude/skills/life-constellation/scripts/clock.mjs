#!/usr/bin/env node
// Builds the clock table (age every 0.1 s) from cast.js and lists every event time.
// Usage: node clock.mjs <project-dir>
//   writes <project-dir>/clock.js and <project-dir>/events.json, prints the event table.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const dir = path.resolve(process.argv[2] || ".");
const cast = loadCast(path.join(dir, "cast.js"));
const { birthAt, endAge, lifeEnd, speed } = cast.clock;
const STEP = 0.1;

function loadCast(file) {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, "utf8"), sandbox);
  return sandbox.window.LC_CAST;
}

function relSpeed(a) {
  if (a <= speed[0][0]) return speed[0][1];
  for (let i = 1; i < speed.length; i++) {
    const [a1, v1] = speed[i];
    const [a0, v0] = speed[i - 1];
    if (a <= a1) return v0 + ((v1 - v0) * (a - a0)) / (a1 - a0);
  }
  return speed[speed.length - 1][1];
}

// Seconds per year, integrated from age 0 (unscaled).
const DA = 0.001;
const T = [0];
for (let a = DA; a <= endAge + 1e-9; a += DA) {
  T.push(T[T.length - 1] + DA / relSpeed(a - DA / 2));
}
const k = (lifeEnd - birthAt) / T[T.length - 1];
const timeOfAge = (a) => {
  if (a <= 0) return birthAt + (a * k) / relSpeed(0);
  if (a >= endAge) return lifeEnd + ((a - endAge) * k) / relSpeed(endAge);
  const i = a / DA;
  const i0 = Math.floor(i);
  return birthAt + k * (T[i0] + (T[Math.min(i0 + 1, T.length - 1)] - T[i0]) * (i - i0));
};
const ageOfTime = (t) => {
  if (t <= birthAt) return ((t - birthAt) * relSpeed(0)) / k;
  if (t >= lifeEnd) return endAge;
  let lo = 0, hi = endAge;
  for (let n = 0; n < 50; n++) {
    const mid = (lo + hi) / 2;
    if (timeOfAge(mid) < t) lo = mid; else hi = mid;
  }
  return (lo + hi) / 2;
};

const e = cast.ending;
const duration = +(lifeEnd + e.black + e.blackFor).toFixed(3);
const ages = [];
for (let i = 0; i * STEP <= lifeEnd + 1e-9; i++) ages.push(+ageOfTime(i * STEP).toFixed(4));
const vEnd = relSpeed(endAge) / k; // years per second for those who live on

fs.writeFileSync(
  path.join(dir, "clock.js"),
  "// Generated by clock.mjs from cast.js – do not edit by hand.\n" +
    "// ages[i] = my age at video time i * step seconds.\n" +
    `window.LC_CLOCK = ${JSON.stringify({ step: STEP, lifeEnd, endAge, birthAt, duration, vEnd: +vEnd.toFixed(5), ages })};\n`,
);

// keep the composition length in sync with the clock
const indexFile = path.join(dir, "index.html");
if (fs.existsSync(indexFile)) {
  const html = fs.readFileSync(indexFile, "utf8");
  fs.writeFileSync(indexFile, html.replace(/(data-composition-id="main"[^>]*?data-duration=")[\d.]+"/, `$1${duration}"`));
}

// ---- events ----
const byId = Object.fromEntries(cast.people.map((p) => [p.id, p]));
const ev = [];
const add = (t, what) => ev.push({ t: +t.toFixed(2), what });
for (const p of cast.people) {
  if (p.type === "joins") add(timeOfAge(p.from) + (p.id === cast.me ? 0.8 : 1.4), `${p.name} joins (${p.from})`);
  if (p.type === "crosses") add(timeOfAge(p.at), `${p.name} crosses (${p.at})`);
  if (p.end?.leaves != null) add(timeOfAge(p.end.leaves) + 0.9, `${p.name} leaves (${p.end.leaves})`);
  if (p.end?.star != null) {
    add(timeOfAge(p.end.star) + 0.7, `${p.name} rises (${p.end.star})`);
    add(timeOfAge(p.end.star) + 2.3, `${p.name} is a star`);
  }
}
add(lifeEnd + 0.6, `${byId[cast.me].name} becomes the biggest star (${endAge})`);
add(lifeEnd + e.linesStart + e.lineEvery * 3, "constellation draws");
add(lifeEnd + e.subtitle + 1.6, "closing text");
add(lifeEnd + e.black + 0.4, "fade to black");
ev.sort((a, b) => a.t - b.t);
fs.writeFileSync(path.join(dir, "events.json"), JSON.stringify({ duration, events: ev }, null, 2));

console.log(`duration ${duration}s · birth ${birthAt}s · age ${endAge} at ${lifeEnd}s · scale ${k.toFixed(4)}`);
for (const a of [0, 5, 10, 20, 30, 40, 50, 60, 70, 80, 85]) console.log(`  age ${String(a).padStart(2)} → ${timeOfAge(a).toFixed(1)} s`);
console.log("\n| s | event |\n|---|---|");
for (const x of ev) console.log(`| ${x.t.toFixed(1)} | ${x.what} |`);
